interface LanguageContextValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, fallback?: string) => string
  label: (group: string, value?: string | null, fallback?: string) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function normalizeLocale(value: string | null | undefined): Locale {
  return SUPPORTED_LOCALES.includes(value as Locale) ? (value as Locale) : DEFAULT_LOCALE
}

function readStoredLocale(): Locale {
  if (typeof window === 'undefined') return DEFAULT_LOCALE
  return normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY))
}

export function getActiveLocale(): Locale {
  return activeLocale
}

export function getIntlLocale(locale = activeLocale): string {
  return locale === 'en' ? 'en-US' : 'ko-KR'
}

function setActiveLocale(locale: Locale) {
  activeLocale = normalizeLocale(locale)
}

function translate(locale: Locale, key: string, fallback?: string): string {
  return messages[locale][key] ?? messages[DEFAULT_LOCALE][key] ?? fallback ?? key
}

function translateLabel(locale: Locale, group: string, value?: string | null, fallback?: string): string {
  if (!value) return fallback ?? '-'
  return enumLabels[locale][group]?.[value] ?? enumLabels[DEFAULT_LOCALE][group]?.[value] ?? fallback ?? value
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const initial = readStoredLocale()
    setActiveLocale(initial)
    return initial
  })

  useEffect(() => {
    setActiveLocale(locale)
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, locale)
    }
  }, [locale])

  const value = useMemo<LanguageContextValue>(
    () => ({
      locale,
      setLocale: (nextLocale) => setLocaleState(normalizeLocale(nextLocale)),
      t: (key, fallback) => translate(locale, key, fallback),
      label: (group, rawValue, fallback) => translateLabel(locale, group, rawValue, fallback),
    }),
    [locale]
  )

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used within LanguageProvider')
  }
  return context
}
